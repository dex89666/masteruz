/** Максимум единиц штучной работы, который считаем без выезда мастера. */
export const MAX_UNIT_QUANTITY = 20;

/** Строки, которые не размножаются вместе с количеством: выезд оплачивается один раз. */
function isPerVisitLine(line: PricedLine): boolean {
  return /выезд|диагностик/i.test(line.name) || /выезд/i.test(line.unit);
}

/** Единицы, которыми считают штучные предметы (в отличие от метража и площади). */
const COUNTABLE_UNITS = new Set([
  'шт', 'шт.', 'штук', 'точка', 'точек', 'ед.', 'ед', 'модуль', 'модуля', 'модулей', 'мод.',
  'створка', 'створки', 'полоса', 'полосы', 'проём', 'проем', 'предмет', 'дерево',
]);
/**
 * Площадь стен — отдельная единица. Клиент называет площадь комнаты по полу,
 * а покраска, обои и штукатурка считаются по стенам; единица подсказывает
 * расчёту, что площадь пола надо пересчитать.
 */
export const WALL_AREA_UNIT = 'м² стен';
/** Единицы площади и метража — работы, которые считаются за м² или погонный метр. */
const AREA_UNITS = new Set(['м²', 'м2', 'кв.м', 'кв. м', WALL_AREA_UNIT]);
/** Упаковка, которую покупают целиком: полтора мешка смеси не продаются. */
const WHOLE_UNITS = new Set(['мешок', 'ведро', 'баллон', 'лист', 'упак.', 'канистра', 'рулон']);
const LENGTH_UNITS = new Set(['м.п.', 'м.п', 'пм', 'пог.м', 'пог. м']);

export type VolumeClass = 'count' | 'area' | 'length';

/** Площадь или метраж, названные клиентом («20 м²», «5 метров»). */
export interface VolumeMeasure {
  value: number;
  unit: 'м²' | 'м.п.';
  /**
   * Что измерено: пол комнаты («комната 16 м²») или сама поверхность
   * («стена 12 м²»). Для работ по стенам площадь пола пересчитывается.
   */
  basis?: 'room' | 'surface';
}

export function volumeClassOf(unit: string): VolumeClass | null {
  const u = unit.trim().toLowerCase();
  if (COUNTABLE_UNITS.has(u)) return 'count';
  if (AREA_UNITS.has(u)) return 'area';
  if (LENGTH_UNITS.has(u)) return 'length';
  return null;
}

/**
 * Разовые строки заказа — не множатся вместе с объёмом: выезд и всё, что
 * помечено единицей «заказ» (автомат в щитке на новую линию, вынос мусора).
 * Три розетки на одной новой линии — это один автомат, а не три.
 */
function isPerOrderLine(line: PricedLine): boolean {
  return isPerVisitLine(line) || line.unit.trim().toLowerCase() === 'заказ';
}

/** Основная работа решения — первая строка труда, которая масштабируется объёмом. */
export function mainWorkLine(variant: Pick<EstimateVariant, 'works'>): PricedLine | undefined {
  return variant.works.find((w) => !isPerOrderLine(w) && w.qty > 0 && volumeClassOf(w.unit) !== null);
}

/** Высота потолка в типовой квартире. */
const CEILING_HEIGHT_M = 2.7;
/** Средняя площадь комнаты, когда названа площадь всей квартиры. */
const ROOM_AREA_M2 = 20;
/** Дверь и окно в каждой комнате, м². */
const OPENINGS_M2 = 3;

/**
 * Площадь стен по площади пола.
 *
 * В комнате 16 м² стен около 40 м²: периметр квадратной комнаты на высоту
 * потолка минус проёмы. Большая площадь считается как несколько комнат по
 * 20 м² — у квартиры есть внутренние стены, одна большая «коробка» дала бы
 * вдвое меньше.
 */
export function wallAreaFromFloor(floorM2: number): number {
  const rooms = Math.max(1, floorM2 / ROOM_AREA_M2);
  const perRoom = floorM2 / rooms;
  return Math.max(1, Math.round(rooms * (4 * Math.sqrt(perRoom) * CEILING_HEIGHT_M - OPENINGS_M2)));
}

/** Предел площади и метража — опечатка «2000 м²» не должна давать смету на дворец. */
const MAX_MEASURE: Record<VolumeMeasure['unit'], number> = { 'м²': 1000, 'м.п.': 500 };

/**
 * На сколько единиц работы уже рассчитано решение.
 *
 * Уровни каталога не обязательно описывают одну единицу: «Замена розетки»
 * рассчитана на одну, «Замена блока розеток (2-3 шт.)» — на три, а
 * «Замена розеток + новая линия» — на четыре. Если этого не учитывать,
 * количество от клиента умножает уже заложенное количество, и три розетки
 * превращаются в двенадцать.
 */
export function solutionBaseQuantity(variant: Pick<EstimateVariant, 'works'>): number {
  // Берём основную работу — первую штучную строку после выезда. Следом в
  // каталоге идут сопутствующие операции: «Установка зеркальных дверей, 2 шт.»
  // при сборке ОДНОГО шкафа. Максимум по всем строкам принимал двери за два
  // шкафа и делил смету пополам.
  const main = variant.works.find(
    (w) => !isPerOrderLine(w) && w.qty > 0 && volumeClassOf(w.unit) === 'count',
  );
  return main ? main.qty : 1;
}

const sumLines = (lines: PricedLine[]): number => lines.reduce((s, l) => s + l.total, 0);

/**
 * Округление цены за единицу с учётом её порядка.
 *
 * Единый шаг в 1 000 сум искажает дешёвые позиции: покос газона стоит
 * 500 сум за м², и округление до тысячи удваивает его — на 200 м² это
 * лишние 100 000 сум в смете. Шаг подбирается под величину цены, чтобы
 * смета не пестрела числами вроде «71 447» и при этом не врала.
 */
export function roundUnitPrice(value: number): number {
  if (!Number.isFinite(value) || value <= 0) return 0;
  if (value < 5_000) return Math.round(value / 100) * 100;
  if (value < 50_000) return Math.round(value / 500) * 500;
  return Math.round(value / 1_000) * 1_000;
}

const recalcTotal = (v: EstimateVariant): number => sumLines(v.works) + sumLines(v.materials);

/**
 * Привести смету к объёму, который назвал клиент.
 *
 * Количество штук («заменить 3 розетки») масштабирует штучные работы,
 * площадь или метраж («покрасить 20 м²») — работы, которые считаются за м²
 * или погонный метр. Масштабируется не «во столько-то раз», а до нужного
 * объёма: каждое решение уже рассчитано на какой-то объём, и его надо учесть.
 *
 * Разовые строки — выезд, автомат в щитке, вынос мусора — остаются как есть:
 * мастер едет один раз, сколько бы розеток ни менял.
 */
export function applyQuantity(
  variants: EstimateVariant[],
  quantity?: number | null,
  measure?: VolumeMeasure | null,
): EstimateVariant[] {
  const hasCount = !!quantity && quantity >= 1;
  const hasMeasure = !!measure && measure.value > 0;
  if (!hasCount && !hasMeasure) return variants;

  return variants.map((v) => {
    const main = mainWorkLine(v);
    const mainClass = main ? volumeClassOf(main.unit) : null;
    const measureClass: VolumeClass | null = hasMeasure ? (measure!.unit === 'м²' ? 'area' : 'length') : null;

    let factor = 1;
    if (hasMeasure && main && mainClass === measureClass) {
      // Работы по стенам: площадь комнаты по полу пересчитываем в площадь стен.
      const onWalls = main.unit.trim().toLowerCase() === WALL_AREA_UNIT && measure!.basis === 'room';
      const target = onWalls ? wallAreaFromFloor(measure!.value) : measure!.value;
      factor = Math.min(target, MAX_MEASURE[measure!.unit]) / main.qty;
    } else if (hasCount) {
      const wanted = Math.min(Math.floor(quantity!), MAX_UNIT_QUANTITY);
      // Без штучной основной работы количество действует как прежний множитель.
      factor = wanted / (mainClass === 'count' && main ? main.qty : 1);
    } else {
      return v;
    }
    if (!Number.isFinite(factor) || Math.abs(factor - 1) < 0.01) return v;

    const scale = (lines: PricedLine[]) =>
      lines.map((l) => {
        if (isPerOrderLine(l)) return l;
        // Дробное число штук и мешков смысла не имеет — округляем вверх:
        // недосчитать хуже, чем показать на единицу больше. Площадь и метраж — до сотых.
        const qty = Math.max(l.qty > 0 ? 0.01 : 0, Math.round(l.qty * factor * 100) / 100);
        const whole = volumeClassOf(l.unit) === 'count' || WHOLE_UNITS.has(l.unit.trim().toLowerCase());
        const rounded = whole ? Math.max(1, Math.ceil(qty)) : qty;
        return { ...l, qty: rounded, total: Math.round(rounded * l.unitPrice) };
      });

    const works = scale(v.works);
    const materials = scale(v.materials);
    const next = { ...v, works, materials };
    return {
      ...next,
      estimatedPrice: recalcTotal(next),
      // Больше объём — больше времени, но не линейно: мастер уже на объекте.
      estimatedDays: Math.max(1, Math.ceil(v.estimatedDays * (1 + Math.max(0, factor - 1) * 0.35))),
    };
  });
}

// Порог, ниже которого расхождение с оценкой AI считаем шумом каталога.
const HINT_MIN_RATIO = 1.3;
// Выше этого AI явно ошибся в масштабе объекта — доверяем каталогу.
const HINT_MAX_RATIO = 5;
// Предел роста ставки труда, чтобы одна аномальная оценка не улетела в космос.
const LABOR_SCALE_CAP = 8;

/**
 * Подтянуть смету к ценовому диапазону, который назвал AI Vision.
 *
 * Применяется ТОЛЬКО к труду. Стоимость материалов остаётся каталожной:
 * хомут, фум-лента и герметик не дорожают оттого, что на фото оказался
 * шкаф-купе вместо тумбы. Раньше коэффициент умножал и материалы —
 * это давало строки вроде «Хомут — 45 000 сум».
 */
export function scaleVariantsToPriceHint(
  variants: EstimateVariant[],
  aiPriceHint?: { min: number; max: number } | null,
): EstimateVariant[] {
  if (!aiPriceHint || aiPriceHint.min <= 0 || aiPriceHint.max < aiPriceHint.min) return variants;
  if (variants.length === 0) return variants;

  const anchor = variants.find((v) => v.tier === 'BETTER') ?? variants[Math.floor(variants.length / 2)];
  const aiMid = (aiPriceHint.min + aiPriceHint.max) / 2;
  const ratio = aiMid / Math.max(anchor.estimatedPrice, 1);
  if (ratio < HINT_MIN_RATIO || ratio > HINT_MAX_RATIO) return variants;

  const anchorLabor = sumLines(anchor.works);
  const anchorMaterials = sumLines(anchor.materials);
  if (anchorLabor <= 0) return variants;

  // Материалы фиксированы → весь недостающий объём добираем ставкой труда.
  const laborScale = Math.min(Math.max((aiMid - anchorMaterials) / anchorLabor, 1), LABOR_SCALE_CAP);
  if (laborScale <= 1.05) return variants;

  return variants.map((v) => {
    const works = v.works.map((w) => {
      const unitPrice = roundUnitPrice(w.unitPrice * laborScale);
      return { ...w, unitPrice, total: Math.round(w.qty * unitPrice) };
    });
    const next = { ...v, works };
    return { ...next, estimatedPrice: recalcTotal(next) };
  });
}

// Ниже этой суммы платный выезд удваивает чек и выглядит накруткой.
const VISIT_FEE_DROP_THRESHOLD = 120_000;

/**
 * Убрать строку выезда из самого дешёвого варианта, если работа копеечная:
 * замена розетки за 50 000 + выезд 50 000 = 100 % накрутки.
 */
export function dropVisitFeeOnCheapVariant(variants: EstimateVariant[]): EstimateVariant[] {
  const good = variants.find((v) => v.tier === 'GOOD');
  if (!good || good.estimatedPrice > VISIT_FEE_DROP_THRESHOLD) return variants;

  return variants.map((v) => {
    if (v.tier !== 'GOOD') return v;
    const works = v.works.filter((w) => !isPerVisitLine(w));
    if (works.length === v.works.length || works.length === 0) return v;
    const next = { ...v, works };
    return { ...next, estimatedPrice: recalcTotal(next) };
  });
}

export interface BuildVariantsOptions {
  /** Количество единиц штучной работы, извлечённое из описания клиента. */
  quantity?: number | null;
  /** Площадь или метраж из описания клиента — для работ за м² и погонный метр. */
  measure?: VolumeMeasure | null;
  /** Уверенность в смете, посчитанная из сигналов (см. computeEstimateConfidence). */
  confidence?: number;
  /**
   * То, что понял Vision: краткое резюме, объекты на фото, материалы.
   *
   * Используется, только если по словам самого клиента проблема не нашлась.
   * Порядок именно такой: слова клиента — истина, зрение — подсказка. Без
   * этого заказ по одной фотографии без текста не находил ничего вообще.
   */
  aiContext?: string;
}

/**
 * Построить 3 варианта (GOOD / BETTER / BEST) из каталога расценок.
 *
 * Порядок применения правил важен:
 *   1. базовые позиции из каталога;
 *   2. умножение на количество единиц («3 розетки»);
 *   3. подтягивание труда к оценке AI, если она существенно выше;
 *   4. снятие выезда с самого дешёвого варианта.
 *
 * Шаг 3 идёт после шага 2 намеренно: AI оценивает весь объём работ целиком,
 * поэтому сравнивать его диапазон нужно с уже умноженной сметой.
 */
export function buildSmartVariants(
  categorySlug: string,
  categoryName: string,
  description: string,
  aiPriceHint?: { min: number; max: number } | null,
  options: BuildVariantsOptions = {},
): { problemName: string; variants: EstimateVariant[] } | null {
  const problem = findProblemByDescription(categorySlug, description, options.aiContext);
  if (!problem) return null;

  // Уверенность одинакова для всех трёх уровней: премиум-вариант не «вернее»
  // базового, он просто дороже. Прежние 0.85 / 0.92 / 0.97 были константами,
  // которые показывались клиенту как измеренная величина.
  const confidence = options.confidence ?? 0.75;

  let variants: EstimateVariant[] = problem.solutions.map((sol) => {
    const works: PricedLine[] = sol.works.map((w) => ({
      name: w.name,
      qty: w.qty,
      unit: w.unit,
      unitPrice: w.unitPrice,
      total: w.qty * w.unitPrice,
    }));
    const materials: PricedLine[] = sol.materials.map((m) => ({
      name: m.name,
      qty: m.qty,
      unit: m.unit,
      unitPrice: m.unitPrice,
      total: m.qty * m.unitPrice,
    }));
    return {
      tier: sol.tier,
      tierLabel: TIER_LABELS[sol.tier] || sol.tier,
      title: sol.title,
      description: sol.description,
      works,
      materials,
      estimatedPrice: sumLines(works) + sumLines(materials),
      estimatedDays: sol.days,
      confidence,
    };
  });

  variants = applyQuantity(variants, options.quantity, options.measure);
  variants = scaleVariantsToPriceHint(variants, aiPriceHint);
  variants = dropVisitFeeOnCheapVariant(variants);

  return { problemName: problem.problemName, variants };
}
